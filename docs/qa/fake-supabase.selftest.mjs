// Self-test: drives the emulator with the REAL @supabase/supabase-js client, using the same call shapes as the app's adapters.
// Usage: node docs/qa/fake-supabase.selftest.mjs   (starts its own emulator on port 3499)
import { spawn } from "node:child_process";
import { createClient } from "@supabase/supabase-js";
const KEY = "selftest-service-key", ANON = "selftest-anon-key";
const em = spawn(process.execPath, [new URL("./fake-supabase.mjs", import.meta.url).pathname], { env: { ...process.env, FAKE_SB_PORT: "3499", FAKE_SB_KEY: KEY, FAKE_SB_ANON_KEY: ANON }, stdio: "ignore" });
await new Promise((r) => setTimeout(r, 600));
let failed = 0;
const check = (n, ok, x = "") => { if (!ok) failed++; console.log(`${ok ? "PASS" : "FAIL"}  ${n}${ok ? "" : "  -> " + x}`); };
const mk = (k) => createClient("http://127.0.0.1:3499", k, { auth: { persistSession: false, autoRefreshToken: false } });
const sb = mk(KEY);
try {
  let r = await sb.from("accounts").insert({ label: "a", email_hash: null, status: "active" }).select().single();
  check("insert.select.single returns row with uuid id + timestamp default", !r.error && /^[0-9a-f-]{36}$/.test(r.data.id) && r.data.status === "active" && /\+00:00$/.test(r.data.created_at), JSON.stringify(r));
  const id = r.data.id;
  r = await sb.from("accounts").insert({ label: "", status: "active" }).select().single();
  check("CHECK violation (label length) -> 400/23514", r.error?.code === "23514" && r.status === 400, JSON.stringify(r.error));
  r = await sb.from("accounts").insert({ label: "x", status: "weird" }).select().single();
  check("CHECK violation (status) -> 23514", r.error?.code === "23514");
  r = await sb.from("accounts").insert({ status: "active" }).select().single();
  check("NOT NULL violation -> 23502", r.error?.code === "23502");
  r = await sb.from("accounts").select("*").eq("id", "not-a-uuid").range(0, 0);
  check("select with non-uuid id -> 400/22P02", r.error?.code === "22P02" && r.status === 400, JSON.stringify(r.error));
  r = await sb.from("accounts").select("*").eq("id", id).range(0, 0);
  check("select eq + range returns 1 row", !r.error && r.data.length === 1);
  r = await sb.from("accounts").select("*").eq("id", "00000000-0000-4000-8000-000000000000").range(0, 0);
  check("select no match -> [] 200", !r.error && r.data.length === 0 && r.status === 200);
  r = await sb.from("accounts").select("*").eq("id", id).single();
  check("single ok", !r.error && r.data.id === id);
  r = await sb.from("accounts").select("*").eq("label", "nope").single();
  check("single with 0 rows -> 406 PGRST116", r.error?.code === "PGRST116" && r.status === 406, JSON.stringify(r.error));
  r = await sb.from("accounts").update({ status: "disabled" }).eq("id", id).select();
  check("update returns changed rows", !r.error && r.data.length === 1 && r.data[0].status === "disabled");
  r = await sb.from("accounts").update({ status: "active" }).eq("id", "00000000-0000-4000-8000-000000000000").select();
  check("update no match -> [] (0 rows)", !r.error && r.data.length === 0);
  r = await sb.from("sessions").upsert({ account_id: id, envelope: "e1", rotated_at: new Date().toISOString() }, { onConflict: "account_id" });
  check("upsert insert path ok (201)", !r.error && r.status === 201, JSON.stringify(r));
  r = await sb.from("sessions").upsert({ account_id: id, envelope: "e2", rotated_at: new Date().toISOString() }, { onConflict: "account_id" });
  r = await sb.from("sessions").select("*").eq("account_id", id).range(0, 0);
  check("upsert merge path updates in place", r.data.length === 1 && r.data[0].envelope === "e2");
  r = await sb.from("sessions").upsert({ account_id: "00000000-0000-4000-8000-000000000000", envelope: "x" }, { onConflict: "account_id" });
  check("FK violation -> 409/23503", r.error?.code === "23503" && r.status === 409, JSON.stringify(r.error));
  r = await sb.from("sessions").upsert({ account_id: id, envelope: "x" }, { onConflict: "envelope" });
  check("on_conflict without unique index -> 42P10", r.error?.code === "42P10");
  r = await sb.from("oauth_clients").insert({ client_id: "c1", redirect_uris: ["https://a"], client_name: "n", created_at: new Date().toISOString() });
  r = await sb.from("oauth_clients").insert({ client_id: "c1", redirect_uris: ["https://a"], client_name: "n" });
  check("duplicate PK -> 409/23505", r.error?.code === "23505" && r.status === 409, JSON.stringify(r.error));
  r = await sb.from("oauth_clients").insert({ client_id: "c2", redirect_uris: [], client_name: "n" });
  check("CHECK cardinality(redirect_uris) -> 23514", r.error?.code === "23514");
  r = await sb.from("usage_counters").upsert({ account_id: id, day: "2026-10-31", kind: "chat", count: 1 }, { onConflict: "account_id,day,kind" });
  r = await sb.from("usage_counters").upsert({ account_id: id, day: "2026-10-31", kind: "chat", count: 2 }, { onConflict: "account_id,day,kind" });
  r = await sb.from("usage_counters").select("*").match({ account_id: id, day: "2026-10-31", kind: "chat" }).range(0, 0);
  check("usage_counters composite upsert + typed read (count number)", r.data[0]?.count === 2, JSON.stringify(r));
  r = await sb.from("login_attempts").insert({ key_hash: "a".repeat(64), attempted_at: new Date().toISOString() }).select().single();
  check("login_attempts identity id is a number", typeof r.data?.id === "number", JSON.stringify(r));
  r = await sb.from("login_attempts").insert({ key_hash: "short" }).select().single();
  check("login_attempts key_hash check", r.error?.code === "23514");
  r = await sb.from("login_attempts").delete().lt("attempted_at", new Date(Date.now() - 1000).toISOString()).eq("key_hash", "a".repeat(64));
  r = await sb.from("login_attempts").select("*").range(0, 9);
  check("delete lt(ISO Z string) leaves newer row", r.data.length === 1);
  r = await sb.from("login_attempts").delete();
  check("DELETE without filter -> 400 21000 (pg-safeupdate)", r.error?.code === "21000", JSON.stringify(r.error));
  r = await sb.from("audit_log").insert({ account_id: id, tool: "t", rpc_id: null, outcome: "ok", at: new Date().toISOString() });
  r = await sb.from("accounts").delete().eq("id", id);
  const tables = await (await fetch("http://127.0.0.1:3499/__qa/tables")).json();
  check("delete cascades sessions/usage, sets audit_log.account_id null", tables.sessions.length === 0 && tables.usage_counters.length === 0 && tables.audit_log[0]?.account_id === null);
  r = await mk("wrong").from("accounts").select("*");
  check("wrong apikey -> 401", r.status === 401);
  r = await mk(ANON).from("accounts").select("*");
  check("anon key -> 401 permission denied (RLS/revoke)", r.status === 401 && r.error?.code === "42501", JSON.stringify(r.error));
  r = await sb.from("nope").select("*");
  check("unknown table -> 404 PGRST205", r.error?.code === "PGRST205");
  r = await sb.from("accounts").select("*", { count: "exact" }).range(0, 0);
  check("count=exact returns count", r.count === 0 && !r.error);
} finally { em.kill(); }
console.log(failed ? `${failed} FAILED` : "emulator self-test: all passed");
process.exit(failed ? 1 : 0);
